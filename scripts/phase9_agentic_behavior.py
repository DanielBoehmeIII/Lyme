def main():
    print("=" * 72)
    print("  Phase 9 — Agentic Model Behavior (Weeks 53-59)")
    print("=" * 72)

    all_data = {}

    # Week 53
    w53 = gen_action_grammar()
    all_data["week53_action_grammar"] = w53
    print(f"\n  Week 53 — Action Grammar: {len(w53)} examples")

    # Week 54
    w54 = gen_react_traces()
    all_data["week54_react_traces"] = w54
    print(f"  Week 54 — ReAct Traces: {len(w54)} examples")

    # Week 55
    w55 = gen_tool_feedback()
    all_data["week55_tool_feedback"] = w55
    print(f"  Week 55 — Tool Feedback: {len(w55)} examples")

    # Week 56
    w56 = gen_stop_conditions()
    all_data["week56_stop_conditions"] = w56
    print(f"  Week 56 — Stop Conditions: {len(w56)} examples")

    # Week 57
    w57 = gen_plan_patch_alignment()
    all_data["week57_plan_patch"] = w57
    print(f"  Week 57 — Plan-Patch Alignment: {len(w57)} examples")

    # Save all data
    for key, examples in all_data.items():
        week_dir = AGENT_DIR / key
        week_dir.mkdir(parents=True, exist_ok=True)
        random.shuffle(examples)
        n = len(examples)
        train = examples[:int(n*0.7)]
        val = examples[int(n*0.7):int(n*0.85)]
        test = examples[int(n*0.85):]
        for split_name, split_exs in [("train", train), ("val", val), ("test", test)]:
            split_dir = week_dir / split_name
            split_dir.mkdir(parents=True, exist_ok=True)
            with open(split_dir / "combined.jsonl", "w") as f:
                for ex in split_exs:
                    f.write(json.dumps(ex) + "\n")
        print(f"    Saved: train={len(train)} val={len(val)} test={len(test)}")

    # Week 58: Runtime config
    runtime = build_runtime()
    runtime_path = AGENT_DIR / "agent_runtime_v2.json"
    runtime_path.write_text(json.dumps(runtime, indent=2))
    print(f"\n  Week 58 — Agent Runtime v2 config: {runtime_path}")

    # Week 59: Eval suite
    eval_suite = build_eval_suite()
    eval_path = AGENT_DIR / "agentic_eval_suite.json"
    eval_path.write_text(json.dumps(eval_suite, indent=2))
    print(f"  Week 59 — Agentic Eval Suite: {eval_path} ({len(EVAL_TASKS)} tasks)")

    total = sum(len(v) for v in all_data.values())
    print(f"\n  Total Phase 9 examples: {total}")
    print("=" * 72)

if __name__ == "__main__":
    main()
