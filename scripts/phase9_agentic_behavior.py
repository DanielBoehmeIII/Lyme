def gen_action_grammar():
    examples = []
    for task in ACTION_TASKS:
        for _ in range(30):
            action_seq = []
            for action, args, result in task["actions"]:
                action_seq.append({
                    "tool_name": action,
                    "arguments": json.loads(args) if args else {},
                    "result_summary": result[:200],
                    "success": True,
                    "latency_ms": random.randint(100, 3000),
                })
            target = "\n".join(f"<{action} args={args}>{result[:40]}..." for action, args, result in task["actions"])
            examples.append({
                "id": f"action-grammar-{random.randint(1000,9999)}",
                "modality": "tool_use",
                "created": datetime.now(timezone.utc).isoformat(),
                "source": "synthetic",
                "difficulty": "medium",
                "instruction": task["instruction"],
                "repo_context": {"repo_name": "agent-project", "language": "Python"},
                "retrieved_files": [{"file_path": "src/main.py", "role": "source", "content_preview": "", "lines": 0, "relevance_score": 1.0}],
                "tool_outputs": action_seq,
                "target_output": target,
                "metadata": {"agentic_training": "action_grammar", "tag": "week53", "num_actions": len(task["actions"])},
            })
    return examples

