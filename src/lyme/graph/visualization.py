    def to_d3_json(self) -> Dict[str, Any]:
        return {
            "nodes": [
                {
                    "id": n.id,
                    "name": n.name,
                    "type": n.node_type.value if hasattr(n.node_type, 'value') else str(n.node_type),
                    "subsystem": n.subsystem,
                    "risk_score": n.risk_score,
                    "import_count": n.import_count,
                    "dependents_count": n.dependents_count,
                }
                for n in self.graph._nodes.values()
            ],
            "links": [
                {
                    "source": e.source_id,
                    "target": e.target_id,
                    "type": e.relation_type.value if hasattr(e.relation_type, 'value') else str(e.relation_type),
                    "confidence": e.confidence,
                    "weight": e.weight,
                }
                for e in self.graph._edges.values()
            ],
        }

    def _html_node_cards(self) -> str:
        sorted_nodes = sorted(
            self.graph._nodes.values(),
            key=lambda n: n.risk_score,
            reverse=True,
        )[:50]
        cards = []
        for n in sorted_nodes:
            risk_class = "risk-high" if n.risk_score >= 0.7 else "risk-med" if n.risk_score >= 0.4 else "risk-low"
            short_name = n.name.split("/")[-1] if "/" in n.name else n.name
            cards.append(
                f'<div class="node-card">'
                f'<span class="name">{short_name}</span>'
                f'<span class="risk {risk_class}">{n.risk_score:.2f}</span>'
                f'<br><small style="color:#8b949e">{n.file_path} | {n.node_type}</small>'
                f'</div>'
            )
        return "\n".join(cards)

    def _html_edge_rows(self) -> str:
        sorted_edges = sorted(
            self.graph._edges.values(),
            key=lambda e: e.confidence,
            reverse=True,
        )[:50]
        rows = []
        for e in sorted_edges:
            src = self.graph.get_node(e.source_id)
            tgt = self.graph.get_node(e.target_id)
            src_name = src.name.split("/")[-1] if src and "/" in src.name else (src.name if src else e.source_id)
            tgt_name = tgt.name.split("/")[-1] if tgt and "/" in tgt.name else (tgt.name if tgt else e.target_id)
            rows.append(
                f"<tr><td>{src_name}</td><td>{tgt_name}</td>"
                f"<td>{e.relation_type.value}</td>"
                f"<td>{e.confidence:.2f}</td>"
                f"<td>{e.weight:.2f}</td></tr>"
            )
        return "\n".join(rows)

    def _html_type_distribution(self) -> str:
        boxes = []
        for rtype, edge_ids in sorted(self.graph._type_index.items(), key=lambda x: -len(x[1])):
            label = rtype.value if hasattr(rtype, 'value') else str(rtype)
            boxes.append(
                f'<div class="stat-box"><h3>{label}</h3>'
                f'<div class="value">{len(edge_ids)}</div></div>'
            )
        return "\n".join(boxes[:8])

    def _risk_color(self, score: float) -> str:
        if score >= 0.7:
            return "#f85149"
        elif score >= 0.4:
            return "#d29922"
        return "#3fb950"

    def _risk_color_hex(self, score: float) -> str:
        if score >= 0.7:
            return "#f85149"
        elif score >= 0.4:
            return "#d29922"
        return "#3fb950"

    def _confidence_color(self, score: float) -> str:
        if score >= 0.7:
            return "#58a6ff"
        elif score >= 0.4:
            return "#a5d6ff"
        return "#8b949e"
