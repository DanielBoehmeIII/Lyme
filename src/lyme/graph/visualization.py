from __future__ import annotations

import json
from typing import Any, Dict, List, Optional, Set

from .causal_graph import CausalGraph, CausalNode, CausalEdge, CausalRelationType


class CausalGraphRenderer:
    def __init__(self, graph: CausalGraph):
        self.graph = graph

    def to_graphviz(self, include_confidence: bool = True) -> str:
        lines = ["digraph CausalGraph {"]
        lines.append("  rankdir=LR;")
        lines.append("  node [shape=box, style=rounded, fontname=monospace];")
        lines.append("  edge [fontname=monospace, fontsize=10];")

        for node in self.graph._nodes.values():
            color = self._risk_color(node.risk_score)
            label = f"{node.name}" + (f"\\n(risk={node.risk_score:.2f})" if include_confidence else "")
            lines.append(f'  "{node.id}" [label="{label}", fillcolor="{color}", style="filled,rounded"];')

        for edge in self.graph._edges.values():
            color = self._confidence_color(edge.confidence)
            style = "dashed" if edge.confidence < 0.5 else "solid"
            label = f"{edge.relation_type.value}" + (f"\\n({edge.confidence:.2f})" if include_confidence else "")
            lines.append(
                f'  "{edge.source_id}" -> "{edge.target_id}" '
                f'[label="{label}", color="{color}", style="{style}", '
                f'penwidth={max(0.5, edge.weight * 3)}];'
            )

        lines.append("}")
        return "\n".join(lines)

    def to_mermaid(self) -> str:
        lines = ["```mermaid", "graph LR;"]
        style_lines = []

        for node in self.graph._nodes.values():
            color = self._risk_color_hex(node.risk_score)
            node_id = node.id.replace("-", "_")
            display_name = node.name.split("/")[-1] if "/" in node.name else node.name
            lines.append(f"    {node_id}[\"{display_name}\"]")
            style_lines.append(f"    style {node_id} fill:{color},stroke:#333,color:#fff;")

        for edge in self.graph._edges.values():
            src = edge.source_id.replace("-", "_")
            tgt = edge.target_id.replace("-", "_")
            label = f"{edge.relation_type.value[:3]}"
            lines.append(f"    {src}-->{tgt}|{label}|;")

        lines.extend(style_lines)
        lines.append("```")
        return "\n".join(lines)

